import assert from 'node:assert/strict';
import { expressionServiceStatus, requestStructuredLlm } from '../api/_llm.js';
for (const key of ['OPENAI_API_KEY', 'OPENROUTER_API_KEY', 'DEEPSEEK_API_KEY', 'ZHIPU_API_KEY', 'LONGCAT_API_KEY', 'PARTNER_API_KEY', 'LLM_PROVIDER', 'EXPRESSION_LLM_PROVIDER', 'OPENAI_BASE_URL']) delete process.env[key];
assert.equal(expressionServiceStatus().available, false);
process.env.OPENAI_API_KEY = 'openai-test-not-real';
process.env.DEEPSEEK_API_KEY = 'deepseek-test-not-real';
process.env.EXPRESSION_LLM_PROVIDER = 'deepseek';
assert.deepEqual(expressionServiceStatus().providers.map(p => p.provider), ['deepseek']);
assert(!JSON.stringify(expressionServiceStatus()).includes('test-not-real'));
const calls = [];
globalThis.fetch = async (url, options) => {
  calls.push({ url, body: JSON.parse(options.body) });
  return { ok: true, json: async () => ({ model: JSON.parse(options.body).model, choices: [{ message: { content: '{"ok":true}' } }] }) };
};
const args = { systemText: 'Return JSON.', userText: 'Test only.', schema: { type: 'object' }, retryOnce: false };
const result = await requestStructuredLlm({ ...args, provider: 'deepseek' });
assert.equal(result.provider, 'deepseek');
assert.equal(calls[0].url, 'https://api.deepseek.com/chat/completions');
await requestStructuredLlm({ ...args, provider: 'openai' });
assert.equal(calls[1].url, 'https://api.openai.com/v1/chat/completions');
assert(!('temperature' in calls[1].body), 'Do not send an unsupported non-default temperature to reasoning models');
process.env.PARTNER_API_KEY = 'partner-test-not-real';
process.env.PARTNER_BASE_URL = 'https://partner.example/v1/';
process.env.PARTNER_MODEL = 'partner-model';
await requestStructuredLlm({ ...args, provider: 'partner' });
assert.equal(calls[2].url, 'https://partner.example/v1/chat/completions');
calls.length = 0;
globalThis.fetch = async url => { calls.push(url); return { ok: false, status: 402, text: async () => 'Insufficient balance' }; };
await assert.rejects(requestStructuredLlm({ ...args, provider: 'deepseek' }));
assert.deepEqual(calls, ['https://api.deepseek.com/chat/completions'], 'Pinned provider must not fall back to a different billing account');
await assert.rejects(requestStructuredLlm({ ...args, provider: 'unknown' }), /unknown_llm_provider/);
console.log('PASS: provider configuration redacts keys; explicit DeepSeek/OpenAI/partner routing; pinned failure never switches billing account. Transport mocked.');
