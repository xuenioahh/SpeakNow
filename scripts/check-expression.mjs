import assert from 'node:assert/strict';
import { summarizeWindow, createReviewClips, compareWithHistory, saveExample, describeMotion, learnedPatterns, rankReviewClips } from '../src/lib/expressionInsights.js';
import { prepareClip } from '../api/expression-review.js';

assert.deepEqual(summarizeWindow(Array.from({ length: 12 }, () => ({}))), {});
assert.deepEqual(summarizeWindow([{ head: 1 }, ...Array.from({ length: 15 }, () => ({}))]), {});
const samples = Array.from({ length: 32 }, (_, i) => ({ time: i / 4, head: i % 2 ? 0.1 : -0.1 }));
const clips = createReviewClips(samples, [{ start: 1, end: 3, text: 'Yes, I agree.' }], 8);
assert.equal(clips[0].text, 'Yes, I agree.');
assert.equal(clips[0].context, ''); // Agreement is never inferred from head movement.
assert(Math.abs(clips[0].metrics.head - 0.1) < 1e-8);
const example = { ...clips[0], context: 'Agreement', decision: 'habit', sessionId: 'one' };
const sameSession = [example, { ...example, id: '8' }, { ...example, id: '16' }];
const candidate = { ...example, sessionId: 'current' };
assert.match(compareWithHistory(candidate, sameSession), /1\/3/);
const history = ['one', 'two', 'three'].map(sessionId => ({ ...example, sessionId }));
assert.match(compareWithHistory(candidate, history), /Within the range/);
assert.match(compareWithHistory({ ...candidate, metrics: { head: 1 } }, history), /not a mistake/);
assert.match(compareWithHistory(candidate, history.map(h => ({ ...h, decision: 'rejected' }))), /0\/3/);
assert.equal(saveExample(history, { ...example, decision: 'rejected' }).length, 3);
assert.equal(describeMotion(samples.map(s => ({ ...s, head: s.head / 100 })), 'head').reversals, 0);
assert.equal(describeMotion(samples.map(s => ({ ...s, time: s.time * 8 })), 'head').reversals, 0, 'Do not bridge missing frames');
assert(describeMotion(samples, 'head').reversals > 2);
assert.equal(learnedPatterns(history)[0].count, 3);
assert.equal(learnedPatterns([...history, { ...example, id: 'another-clip' }])[0].count, 3);
assert.equal(learnedPatterns(history.map(h => ({ ...h, decision: 'rejected' }))).length, 0);
assert.match(compareWithHistory(candidate, history.map(h => ({ ...h, featureVersion: 1 }))), /0\/3/);
const poor = { ...candidate, id: 'poor', coverage: 0.1, metrics: {} };
assert.notEqual(rankReviewClips([poor, candidate], history)[0].id, 'poor');
assert.equal(createReviewClips(samples, [{ start: 0, end: 5, text: 'Done.' }], 8)[0].end, 5);
const prepared = prepareClip({ ...candidate, baseline: { sessions: 3, differences: ['head'] } });
assert(prepared.trajectory.length > 0);
assert(Number.isFinite(prepared.movementVariation.head));
assert.equal(prepared.personalBaseline.sessions, 3);
assert.equal(prepareClip({ ...candidate, context: '', text: 'No, I disagree.' }).confirmedContext, '');
assert(!('trajectory' in saveExample([], candidate)[0]));
assert.match(compareWithHistory({ ...candidate, motion: { head: { reversals: 0 } } }, history), /not a mistake/, 'Compare motion rhythm even when variation is unchanged');
const longSession = [...history.slice(0, 2), ...Array.from({ length: 80 }, (_, id) => ({ ...history[2], id: String(id), metrics: { head: 5 } }))];
assert.match(compareWithHistory(candidate, longSession), /Within the range/, 'One long outlier session must not dominate');
assert.equal(createReviewClips(samples, [], 1.5)[0].end, 1.5, 'Retain short recordings for manual review');
console.log('PASS: missing evidence, temporal pairing, noise/gap rejection, motion trajectories, independent sessions, recurring patterns, feature migration, prioritization and numeric model payload.');
